import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import puppeteer from 'puppeteer-core';
const url = 'http://localhost:4335/ayun-pad/';
const server = spawn(process.execPath, ['node_modules/vite/bin/vite.js', 'preview', '--port', '4335', '--strictPort'], { stdio: 'ignore' });
const sleep = ms => new Promise(r => setTimeout(r, ms));
let browser;
try {
  for (let i = 0; i < 60; i++) { try { if ((await fetch(url)).ok) break; } catch {} await sleep(200); }
  browser = await puppeteer.launch({ executablePath: process.env.CHROME ?? '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true, args: ['--disable-gpu'] });
  const page = await browser.newPage(); const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.setViewport({ width: 1440, height: 1000 }); await page.goto(url, { waitUntil: 'networkidle0' });
  await page.waitForSelector('.editor'); await page.$eval('.addnote', e => e.click());
  await page.waitForFunction(() => document.querySelector('.editor')?.textContent === '');
  await page.evaluate(() => {
    const shapes = window.__ayunpad.doc().shapes;
    const anchor = (x, y) => ({ l: null, r: 0, x, y });
    for (const [i, x] of [10, 30].entries()) shapes.set(`rect-${i}`, { id: `rect-${i}`, t: 'rect', a: anchor(x, 20), b: anchor(x + 10, 30), c: 'r', w: .2, z: i });
    shapes.set('text-group', { id: 'text-group', t: 'text', a: anchor(50, 20), bw: 30, text: 'Group note', c: 'k', w: .2, z: 2 });
  });
  await page.waitForSelector('.tbox'); await page.click('.tb-draw'); await page.waitForSelector('.drawbar');
  await page.evaluate(() => document.activeElement?.blur());
  const mod = await page.evaluate(() => /Mac/.test(navigator.platform) ? 'Meta' : 'Control');
  const key = async (code, shift = false) => { await page.keyboard.down(mod); if (shift) await page.keyboard.down('Shift'); await page.keyboard.press(code); if (shift) await page.keyboard.up('Shift'); await page.keyboard.up(mod); };
  const shapes = () => page.evaluate(() => [...window.__ayunpad.doc().shapes.values()]);
  await key('KeyA'); await key('KeyG');
  await page.waitForFunction(() => [...window.__ayunpad.doc().shapes.values()].every(s => s.group));
  let saved = await shapes(); const group = saved[0].group;
  assert.equal(new Set(saved.map(s => s.group)).size, 1);
  console.log('ok  ⌘G로 도형 두 개와 글상자를 한 그룹으로 저장');
  await page.keyboard.press('Escape');
  const point = await page.$eval('.shapes-layer', e => { const r = e.getBoundingClientRect(); const ppm = r.width / (e.offsetWidth / (96 / 25.4)); return { x: r.x + 10.2 * ppm, y: r.y + 25 * ppm, ppm }; });
  await page.mouse.move(point.x, point.y); await page.mouse.down(); await page.mouse.move(point.x + 15 * point.ppm, point.y, { steps: 10 }); await page.mouse.up();
  await page.waitForFunction(() => window.__ayunpad.doc().shapes.get('rect-0').a.x > 20);
  saved = await shapes();
  assert.ok(Math.abs(saved.find(s => s.id === 'rect-1').a.x - 45) < .6);
  assert.ok(Math.abs(saved.find(s => s.id === 'text-group').a.x - 65) < .6);
  console.log('ok  구성원 하나를 끌면 도형 · 글상자가 함께 이동');
  await key('KeyD');
  await page.waitForFunction(() => window.__ayunpad.doc().shapes.size === 6);
  saved = await shapes(); const copies = saved.filter(s => !['rect-0', 'rect-1', 'text-group'].includes(s.id));
  assert.equal(new Set(copies.map(s => s.group)).size, 1); assert.notEqual(copies[0].group, group);
  console.log('ok  그룹 복제는 원본과 분리된 새 그룹으로 유지');
  await key('KeyG', true);
  await page.waitForFunction(() => [...window.__ayunpad.doc().shapes.values()].filter(s => !s.group).length === 3);
  assert.equal((await shapes()).filter(s => s.group === group).length, 3);
  console.log('ok  ⌘⇧G로 선택한 복사본 그룹만 해제');
  await key('KeyZ');
  await page.waitForFunction(() => [...window.__ayunpad.doc().shapes.values()].every(s => s.group));
  console.log('ok  그룹 해제를 ⌘Z 한 번으로 되돌림');
  await sleep(250); await page.reload({ waitUntil: 'networkidle0' }); await page.waitForSelector('.tbox');
  saved = await shapes(); assert.equal(new Set(saved.map(s => s.group)).size, 2);
  console.log('ok  새로고침 뒤 두 그룹 관계 보존');
  await page.click('.more-btn'); await page.$$eval('.menu.more button[role=menuitem]', buttons => buttons.find(b => b.textContent.startsWith('인쇄 미리보기')).click()); await page.waitForSelector('.pages.a4 .psheet');
  const element = await page.$('.pages [data-sid="rect-0"]');
  const rect = await element.boundingBox();
  const before = await shapes();
  await page.mouse.move(rect.x + 1, rect.y + rect.height / 2); await page.mouse.down(); await page.mouse.move(rect.x + 1 + 40, rect.y + rect.height / 2, { steps: 10 }); await page.mouse.up();
  await page.waitForFunction(x => window.__ayunpad.doc().shapes.get('rect-0').a.x > x + 2, {}, before.find(s => s.id === 'rect-0').a.x);
  saved = await shapes(); const delta = saved.find(s => s.id === 'rect-0').a.x - before.find(s => s.id === 'rect-0').a.x;
  for (const old of before.filter(s => s.group === group)) assert.ok(Math.abs(saved.find(s => s.id === old.id).a.x - old.a.x - delta) < .1);
  for (const old of before.filter(s => s.group !== group)) assert.equal(saved.find(s => s.id === old.id).a.x, old.a.x);
  assert.deepEqual(errors, []);
  console.log('ok  A4 보기에서도 그룹 전체만 함께 이동 · 다른 그룹 유지 · 실행 오류 없음');
} finally { await browser?.close(); server.kill(); }
