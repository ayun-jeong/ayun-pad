import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import puppeteer from 'puppeteer-core';
const port = 4330;
const url = `http://localhost:${port}/ayun-pad/`;
const server = spawn(process.execPath, ['node_modules/vite/bin/vite.js', 'preview', '--port', String(port), '--strictPort'], { stdio: 'ignore' });
const pause = (ms) => new Promise((r) => setTimeout(r, ms));
let browser;
const check = (condition, message) => { assert.ok(condition, message); console.log(`ok  ${message}`); };
try {
  for (let i = 0; i < 60; i++) { try { if ((await fetch(url)).ok) break; } catch {} await pause(250); }
  browser = await puppeteer.launch({ executablePath: process.env.CHROME ?? '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true, pipe: true, enableExtensions: true, args: ['--disable-gpu'] });
  const page = await browser.newPage();
  const errors = [];
  page.on('pageerror', (e) => errors.push(e.message));
  await page.setViewport({ width: 1440, height: 1000 });
  await page.goto(url, { waitUntil: 'networkidle0' });
  await page.waitForSelector('.editor');
  const paperWidth = await page.$eval('.paper', (e) => e.offsetWidth);
  check(Math.abs(paperWidth - 105 * 96 / 25.4) < 2, '기본 편집은 105mm 반쪽부터 시작');
  await page.$eval('.addnote', e => e.click());
  await page.waitForFunction(() => document.querySelector('.editor')?.textContent === '', { timeout: 5000 }).catch(async e => { console.log('startup diagnostics', await page.evaluate(() => ({ title: document.querySelector('.crumb input')?.value, text: [...document.querySelectorAll('.editor')].map(e => e.textContent.slice(0, 200)), notes: [...document.querySelectorAll('.note-item')].map(e => e.textContent), html: document.querySelector('.desk')?.innerHTML.slice(0, 1000) })), errors); throw e; });
  await page.click('.paper-width-options button:first-child');
  await page.waitForFunction(() => Math.abs(document.querySelector('.paper').offsetWidth - 105 * 96 / 25.4) < 2 && document.querySelector('.shapes-svg').viewBox.baseVal.width < 101);
  check(await page.$eval('.paper-width-options button:first-child', e => e.getAttribute('aria-pressed') === 'true'), '반쪽 편집을 선택하면 105mm 종이와 그림 좌표가 함께 전환');
  await pause(250); // IndexedDB 쓰기 거래가 끝난 뒤 재시작한다.
  await page.reload({ waitUntil: 'networkidle0' });
  await page.waitForSelector('.editor');
  await page.waitForFunction(() => Math.abs(document.querySelector('.paper').offsetWidth - 105 * 96 / 25.4) < 2);
  check(true, '노트별 반쪽 편집 설정을 새로고침 뒤에도 유지');
  await page.click('.paper-width-options button:last-child');
  await page.waitForFunction(() => document.querySelector('.folded-snapshots .psheet')?.offsetWidth > 790 && document.querySelector('.fold-live-window .shapes-svg').viewBox.baseVal.width < 101);
  check(await page.$eval('.paper-width-options button:last-child', e => e.getAttribute('aria-pressed') === 'true'), '한 장 편집은 105mm 반쪽 두 개를 좌우로 펼침');
  const noteURL = page.url();
  const layer = await page.$eval('.folded-snapshots .phalf[data-half="1"] .pwin', (e) => { const r = e.getBoundingClientRect(); return { x: r.x, y: r.y, w: r.width }; });
  await page.mouse.click(layer.x + layer.w * .6, layer.y + 150);
  await page.waitForSelector('.tbox.tedit .tb-edit');
  await page.keyboard.type('A4 right side');
  await page.keyboard.press('Escape');
  await page.waitForFunction(() => [...window.__ayunpad.doc().shapes.values()].some((s) => s.text === 'A4 right side'));
  const shapeX = await page.evaluate(() => [...window.__ayunpad.doc().shapes.values()][0].a.x);
  check(shapeX < 100 && await page.evaluate(() => [...window.__ayunpad.doc().shapes.values()][0].a.y > 291), '오른쪽 글상자를 1-2의 좌표로 생성 · 저장');
  await page.click('.fold-live-window .tbox', { count: 2 });
  await page.waitForSelector('.tb-grip', { visible: true });
  const grip = await page.$('.fold-live-window .tb-grip');
  if (grip) {
    const r = await grip.boundingBox();
    await page.mouse.move(r.x + r.width / 2, r.y + r.height / 2); await page.mouse.down(); await page.mouse.move(r.x - 100, r.y + 60, { steps: 8 }); await page.mouse.up();
    await page.waitForFunction((before) => [...window.__ayunpad.doc().shapes.values()][0].a.x < before - 10, {}, shapeX);
    check(true, 'A4 전체 편집에서 글상자 자유 이동');
  }
  await page.click('.references-btn');
  await page.waitForSelector('.reference-panel');
  const action = async (label) => { const b = await page.$(`.reference-actions button ::-p-text(${label})`); await b.click(); };
  await page.waitForFunction(() => !document.querySelector('.reference-actions button').disabled);
  await action('메모');
  await page.waitForSelector('.reference-markdown[contenteditable="true"]');
  await page.type('.reference-markdown[contenteditable="true"]', 'Reference saved');
  await pause(200);
  await page.reload({ waitUntil: 'networkidle0' });
  await page.waitForSelector('.editor');
  await page.click('.references-btn');
  await page.waitForSelector('.reference-markdown[contenteditable="true"]');
  check(await page.$eval('.reference-markdown[contenteditable="true"]', (e) => e.textContent === 'Reference saved'), '참고 메모가 새로고침 뒤에도 복원');
  await action('기존 노트');
  const sourceNote = await page.$eval('#reference-note option:not([disabled])', (e) => e.value);
  await page.select('#reference-note', sourceNote);
  await page.waitForFunction(() => document.querySelector('.reference-note')?.textContent.includes('경영학'));
  check(true, '기존 노트의 본문을 참고 자료로 표시');
  await action('웹사이트');
  await page.type('#reference-address', 'javascript:alert(1)');
  await page.click('.reference-form button');
  await page.waitForSelector('.reference-error');
  check(!(await page.$('.reference-frame')), '실행 가능한 웹주소를 차단');
  await page.$eval('#reference-address', (e) => { e.value = ''; e.dispatchEvent(new Event('input', { bubbles: true })); });
  await page.click('#reference-address', { count: 3 }); await page.keyboard.type(url + 'lab/keys.html');
  await page.click('.reference-form button');
  await page.waitForSelector('.reference-frame');
  check(true, '웹사이트를 자료 판에 열기');
  const input = await page.$('.reference-panel input[type=file]');
  mkdirSync('/tmp/ayunpad-qa', { recursive: true });
  const pdfObjects = ['<< /Type /Catalog /Pages 2 0 R >>', '<< /Type /Pages /Kids [3 0 R] /Count 1 >>', '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>', '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>', '<< /Length 49 >>\nstream\nBT /F1 20 Tf 50 770 Td (Reference PDF) Tj ET\nendstream'];
  let pdf = '%PDF-1.4\n'; const offsets = [0];
  for (const [i, obj] of pdfObjects.entries()) { offsets.push(Buffer.byteLength(pdf)); pdf += `${i + 1} 0 obj\n${obj}\nendobj\n`; }
  const xref = Buffer.byteLength(pdf);
  pdf += `xref\n0 6\n0000000000 65535 f \n${offsets.slice(1).map(n => String(n).padStart(10, '0') + ' 00000 n ').join('\n')}\ntrailer\n<< /Size 6 /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF`;
  writeFileSync('/tmp/ayunpad-qa/reference.pdf', pdf);
  await input.uploadFile('/tmp/ayunpad-qa/reference.pdf');
  await page.waitForSelector('.reference-file-link');
  check(true, 'PDF 파일 저장 · 뷰어 열기');
  await input.uploadFile(path.resolve('public/icon-192.png'));
  await page.waitForSelector('.reference-image');
  check(true, '이미지 파일 업로드 · 보기');
  // Resize divider and check both work areas retain usable dimensions.
  const divider = await page.$('.reference-resizer');
  await divider.focus(); await page.keyboard.press('ArrowRight');
  check(await divider.evaluate((e) => Number(e.getAttribute('aria-valuenow')) === 44), '키보드로 자료 · 필기 폭 조절');
  await page.click('button[aria-label="참고 자료 닫기"]');
  const other = await browser.newPage();
  await other.setViewport({ width: 520, height: 850 });
  await other.goto(noteURL + '&panel=1', { waitUntil: 'networkidle0' });
  await other.waitForSelector('.editor');
  const id = await page.evaluate(() => window.__ayunpad.doc().id);
  check(await other.evaluate(() => window.__ayunpad.doc().id) === id, '작은 창에서 같은 노트 열기');
  await page.evaluate(() => { const doc = window.__ayunpad.doc(); const s = [...doc.shapes.values()][0]; doc.shapes.set(s.id, { ...s, text: 'Synced to panel' }); });
  await other.waitForFunction(() => [...window.__ayunpad.doc().shapes.values()].some((s) => s.text === 'Synced to panel'));
  await other.evaluate(() => { const doc = window.__ayunpad.doc(); const s = [...doc.shapes.values()][0]; doc.shapes.set(s.id, { ...s, text: 'Synced to main' }); });
  await page.waitForFunction(() => [...window.__ayunpad.doc().shapes.values()].some((s) => s.text === 'Synced to main'));
  check(true, '로그인 없이 두 창에서 양방향 실시간 동기화');
  await other.click('.crumb input', { count: 3 });
  await other.keyboard.press('Backspace');
  await other.keyboard.type('Panel title');
  await pause(300);
  await page.waitForFunction(() => document.querySelector('.crumb input').value === 'Panel title');
  check(true, '창 사이 노트 제목 · 목록 동기화');
  // Validate full-width print: no fold or lost right side.
  await page.keyboard.down('Alt'); await page.keyboard.press('Digit3'); await page.keyboard.up('Alt');
  await page.waitForSelector('.pages .phalf');
  check(await page.$eval('.pages .psheet', (e) => e.offsetWidth > 790), 'A4 미리보기도 반쪽 두 개를 나란히 배치');
  // Extension gets top-level pad storage via the declared host permission.
  const extensionId = await browser.installExtension(path.resolve('extension'));
  const panel = await browser.newPage();
  panel.on('pageerror', e => console.log('extension error', e.message));
  await panel.goto(`chrome-extension://${extensionId}/sidepanel.html`);
  await panel.click('#settings');
  await panel.$eval('#address', (e, value) => { e.value = value; }, url); await panel.$eval('#config', e => e.requestSubmit());
  await pause(300);
  await panel.waitForFunction(() => document.querySelector('#pad').src.startsWith('http://localhost'));
  let pad;
  for (let i = 0; i < 40; i++) { pad = panel.frames().find((f) => f.url().startsWith(url)); if (pad && await pad.$('.editor')) break; await pause(250); }
  await pad.waitForSelector('.editor');
  check(await pad.evaluate(() => window.__ayunpad.doc().id) === id, '확장 프로그램 iframe에서 기존 로컬 노트를 공유');
  await pad.evaluate(() => { const d = window.__ayunpad.doc(); const s = [...d.shapes.values()][0]; d.shapes.set(s.id, { ...s, text: 'From extension' }); });
  await page.waitForFunction(() => [...window.__ayunpad.doc().shapes.values()].some((s) => s.text === 'From extension'));
  check(true, '확장 사이드 패널과 본창 실시간 동기화');
  await panel.evaluate(() => document.querySelector('#pad').contentWindow.postMessage({ type: 'ayunpad:capture', title: 'Captured source', url: 'https://example.com/article', text: 'Selected passage' }, new URL(document.querySelector('#pad').src).origin));
  await pad.waitForSelector('.reference-markdown');
  check(await pad.$eval('.reference-markdown', e => e.textContent.includes('Selected passage') && e.textContent.includes('https://example.com/article')), '확장에서 선택한 글과 출처를 노트 참고 자료에 저장');
  check(errors.length === 0, `앱 실행 오류 없음: ${errors.join(', ')}`);
  await other.close();
  await page.bringToFront();
  await page.click('.paper-width-options button:last-child');
  await page.click('.references-btn');
  await page.waitForSelector('.reference-tabs');
  await page.$$eval('.reference-tabs button', buttons => buttons.find(b => b.textContent === '새 메모').click());
  mkdirSync('/tmp/ayunpad-qa', { recursive: true });
  await pause(300);
  await page.screenshot({ path: '/tmp/ayunpad-qa/workspace.png' });
  await page.evaluate(() => window.dispatchEvent(new Event('beforeprint')));
  check(await page.$eval('.print-root .psheet', e => e.querySelectorAll('.phalf').length === 2 && e.querySelector('.phalf').style.width === '105mm'), '인쇄도 105mm 반쪽 두 개로 A4 한 장을 구성');
  await page.setViewport({ width: 390, height: 844 });
  if (!(await page.$eval('.side', e => e.classList.contains('hidden')))) await page.$eval('.side-backdrop', e => e.click());
  await page.waitForSelector('.side.hidden');
  await pause(300);
  check(await page.$eval('.top', e => e.scrollWidth <= e.clientWidth), '휴대폰에서도 위쪽 도구 막대가 화면에 맞음');
  await page.screenshot({ path: '/tmp/ayunpad-qa/mobile.png' });
  await panel.bringToFront();
  await panel.evaluate(async () => {
    const current = await chrome.windows.getCurrent();
    document.querySelector('#settings').addEventListener('click', () => {
      chrome.sidePanel.open({ windowId: current.id }).then(() => { window.nativeOpened = true; }).catch(e => { window.nativeError = e.message; });
    }, { once: true });
  });
  await panel.click('#settings');
  await panel.waitForFunction(() => window.nativeOpened || window.nativeError);
  check(await panel.evaluate(() => window.nativeOpened), 'Chrome 네이티브 사이드 패널 열기');
  await panel.evaluate(async () => { const current = await chrome.windows.getCurrent(); await chrome.sidePanel.close({ windowId: current.id }); });
  await panel.close();
  console.log('전체 작업 공간 검증 통과');
} finally { await browser?.close(); server.kill(); }
