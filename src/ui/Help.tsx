export function Help({ onClose }: { onClose(): void }) {
  return (
    <div className="overlay" onClick={onClose}>
      <section className="help" role="dialog" aria-label="단축키" onClick={(e) => e.stopPropagation()}>
        <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center' }}>
          <h3>단축키</h3>
          <button type="button" className="mini" onClick={onClose} aria-label="닫기">
            ×
          </button>
        </div>
        <p style={{ margin: 0, color: 'var(--ink-2)' }}>한글 상태 그대로 눌러도 됩니다. 꺾쇠 줄과 대제목은 따로 칠하지 않아도 빨강과 단계별 형광펜(제목 색의 다음 색)이 들어갑니다.</p>
        <div className="groups">
          {GROUPS.map((g) => (
            <div key={g.title}>
              <h4>{g.title}</h4>
              <dl>
                {g.rows.map(([k, d]) => (
                  <div key={k} style={{ display: 'contents' }}>
                    <dt>
                      {sym(k)
                        .split(' ')
                        .map((x) => (
                          <kbd key={x} style={{ marginRight: 3 }}>
                            {x}
                          </kbd>
                        ))}
                    </dt>
                    <dd>{d}</dd>
                  </div>
                ))}
              </dl>
            </div>
          ))}
        </div>
        <p className="help-foot">
          시험 페이지: <a href="lab/keys.html">단축키 시험</a> · <a href="lab/print.html">인쇄 시험</a>
        </p>
      </section>
    </div>
  );
}
